//! Frame-based whole-app record/replay harness for LÖVE games.
//!
//! A generated Lua driver loads the game's `conf.lua`/`main.lua` under the headless LÖVE
//! stub owned by `codegen_lua`, calls `love.load()` once, then feeds a deterministic
//! sequence of frame events (`update`, `draw`, input callbacks). After every frame it
//! hashes a curated state snapshot with a pure-Lua FNV-1a 64-bit hash and appends the
//! events plus the hash to a JSONL trace. `replay` re-runs the events read back from
//! that trace in a fresh Lua state and checks that every hash matches.

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::walk::Canonical;
use anyhow::{Context, Result, bail};

/// Reusable accessor for the headless stub owned by `codegen_lua` — this module never
/// edits that file, it only reads the public constant.
pub fn headless_stub() -> &'static str {
    crate::codegen_lua::HEADLESS_STUB_LUA
}

/// Reusable accessor for the minimal JSON codec owned by `codegen_lua`.
pub fn codec() -> &'static str {
    crate::codegen_lua::CODEC_LUA
}

/// Pure-Lua FNV-1a 64 + canonical serializer. Kept separate from the driver so it can
/// be tested on its own against independent reference vectors.
pub const HASH_LUA: &str = r##"
-- Pure-Lua FNV-1a 64-bit-ish hash. Lua numbers are doubles, so the 64-bit state is held
-- in two exact 32-bit lanes; every multiply stays below 2^53 and needs no C modules.
local TWO32 = 4294967296

local function bxor8(a, b)
  local out, bit = 0, 1
  for _ = 1, 8 do
    if (a % 2) ~= (b % 2) then out = out + bit end
    a = math.floor(a / 2); b = math.floor(b / 2); bit = bit * 2
  end
  return out
end

local PRIME_HI, PRIME_LO = 0x100, 0x1b3               -- 0x00000100000001b3
local OFFSET_HI, OFFSET_LO = 0xcbf29ce4, 0x84222325    -- 0xcbf29ce484222325

local function fnv_mul(hi, lo)
  -- (hi*2^32 + lo) * (PRIME_HI*2^32 + PRIME_LO) mod 2^64. The hi*PRIME_HI term
  -- sits at bit 64 and is dropped, so only the cross terms feed the high lane.
  local lo_lo = lo * PRIME_LO
  local carry = math.floor(lo_lo / TWO32)
  local new_lo = lo_lo - carry * TWO32
  local mid = lo * PRIME_HI + hi * PRIME_LO + carry
  local new_hi = mid % TWO32
  return new_hi, new_lo
end

local function fnv_byte(hi, lo, b)
  local low = lo % 256
  lo = lo - low + bxor8(low, b)
  return fnv_mul(hi, lo)
end

local MAX_DEPTH = 8

local function canon(v, depth, seen)
  local t = type(v)
  if t == 'nil' then return 'n' end
  if t == 'boolean' then return v and 'T' or 'F' end
  if t == 'number' then
    if v ~= v then return 'N' end
    if v == math.huge then return 'I' end
    if v == -math.huge then return 'i' end
    return string.format('%.17g', v)
  end
  if t == 'string' then
    if #v > 512 then return 's' .. #v .. ':' .. v:sub(1, 512) end
    return 's' .. #v .. ':' .. v
  end
  -- Functions and userdata never contribute addresses (that would break determinism).
  if t == 'function' then return 'f' end
  if t == 'userdata' or t == 'thread' then return 'u' end
  if t ~= 'table' then return '?' end
  if depth >= MAX_DEPTH then return 'D' end
  if seen[v] then return 'C' end
  seen[v] = true
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = k end
  table.sort(keys, function(a, b)
    local ta, tb = type(a), type(b)
    if ta == 'number' and tb == 'number' then return a < b end
    if ta == 'number' then return true end
    if tb == 'number' then return false end
    return tostring(a) < tostring(b)
  end)
  local parts = {}
  for i = 1, #keys do
    local k = keys[i]
    parts[i] = canon(k, depth + 1, seen) .. '=' .. canon(v[k], depth + 1, seen)
  end
  seen[v] = nil
  return '{' .. table.concat(parts, ',') .. '}'
end

local function hash_string(text)
  local hi, lo = OFFSET_HI, OFFSET_LO
  for i = 1, #text do
    hi, lo = fnv_byte(hi, lo, text:byte(i))
  end
  return string.format('%04x%04x%04x%04x',
    math.floor(hi / 65536), hi % 65536, math.floor(lo / 65536), lo % 65536)
end

local function hash_value(v)
  return hash_string(canon(v, 0, {}))
end
"##;

const DRIVER_LUA: &str = r##"
-- Generated by rust-anything: frame record/replay driver for a whole LÖVE app.
local codec = require('rust_anything_codec')
require('rust_anything_headless_stub')
local unpack_ = table.unpack or unpack

local args = { ... }
local mode, root, trace_path, frames_str, summary_path =
  args[1], args[2], args[3], tonumber(args[4]) or 0, args[5]
local frames = math.floor(frames_str)

-- Deterministic snapshot of engine probes, top-level scalar globals and a few named
-- state tables. Only simple values are hashed: no function pointers, no userdata, no
-- wall clock. The headless stub makes time and randomness reproducible across runs.
local STATE_NAMES = { 'Game', 'game', 'STATE', 'state', 'Player', 'player' }
local current_frame = 0
local function state_snapshot()
  local snap = {
    frame = current_frame,
    timer = { _G.love.timer.getTime(), _G.love.timer.getDelta() },
    rng = _G.love.math.getRandomSeed and _G.love.math.getRandomSeed() or 0,
    color = { _G.love.graphics.getColor() },
    background = { _G.love.graphics.getBackgroundColor() },
    title = _G.love.window.getTitle(),
    globals = {}
  }
  for k, v in pairs(_G) do
    local tv = type(v)
    if type(k) == 'string' and (tv == 'number' or tv == 'string' or tv == 'boolean') then
      snap.globals[k] = v
    end
  end
  for _, name in ipairs(STATE_NAMES) do
    if type(_G[name]) == 'table' then snap[name] = _G[name] end
  end
  return snap
end

local function fail(where, err)
  local message = where .. ': ' .. tostring(err)
  local f = io.open(summary_path, 'w')
  if f then f:write(codec.encode({ error = message })); f:close() end
  io.stderr:write('ERROR ' .. message .. '\n')
  os.exit(1)
end

local function load_game_file(name, path)
  local chunk, err = loadfile(path)
  if not chunk then fail('loading ' .. name, err) end
  local ok, perr = pcall(chunk)
  if not ok then fail('running ' .. name, perr) end
end

-- LÖVE's startup order: conf.lua (defines love.conf), love.conf(t), main.lua, love.load().
load_game_file('conf.lua', root .. '/conf.lua')
if type(_G.love.conf) == 'function' then
  local ok, err = pcall(_G.love.conf, { window = {}, modules = {} })
  if not ok then fail('love.conf', err) end
end
load_game_file('main.lua', root .. '/main.lua')
if type(_G.love.load) == 'function' then
  local ok, err = pcall(_G.love.load)
  if not ok then fail('love.load', err) end
end

local function apply_event(ev, frame)
  local fn = ev and ev['fn']
  local target = type(fn) == 'string' and _G.love and _G.love[fn] or nil
  if type(target) ~= 'function' then return false end
  local argv = ev.args or {}
  local ok, err = pcall(target, unpack_(argv, 1, #argv))
  if not ok then fail('frame ' .. frame .. ' ' .. fn, err) end
  return true
end

-- A fixed, replayable input schedule; callbacks the game does not define are skipped.
local function make_events(frame)
  local ev = {
    { ['fn'] = 'update', args = { 1 / 60 } },
    { ['fn'] = 'draw', args = {} }
  }
  if frame % 5 == 1 then ev[#ev + 1] = { ['fn'] = 'keypressed', args = { 'space' } } end
  if frame % 5 == 2 then ev[#ev + 1] = { ['fn'] = 'keyreleased', args = { 'space' } } end
  if frame % 7 == 3 then ev[#ev + 1] = { ['fn'] = 'mousepressed', args = { 1, 100, 200, false } } end
  if frame % 7 == 4 then ev[#ev + 1] = { ['fn'] = 'mousereleased', args = { 1, 100, 200, false } } end
  if frame % 11 == 5 then ev[#ev + 1] = { ['fn'] = 'mousemoved', args = { 100, 200, 0, 0 } } end
  return ev
end

if mode == 'record' then
  local out = io.open(trace_path, 'w')
  if not out then fail('opening trace ' .. trace_path, 'cannot write') end
  for frame = 1, frames do
    local events = make_events(frame)
    for _, ev in ipairs(events) do apply_event(ev, frame) end
    current_frame = frame
    local hash = hash_value(state_snapshot())
    out:write(codec.encode({ frame = frame, events = events, hash = hash }), '\n')
  end
  out:close()
  local f = io.open(summary_path, 'w')
  if f then f:write(codec.encode({ frames = frames, recorded = frames })); f:close() end
  print('recorded ' .. frames .. ' frames -> ' .. trace_path)
elseif mode == 'replay' then
  local summary = { frames = 0, matched = 0, mismatches = {} }
  for line in io.lines(trace_path) do
    if line ~= '' then
      local rec = codec.decode(line)
      if type(rec) == 'table' and rec.frame then
        for _, ev in ipairs(rec.events or {}) do apply_event(ev, rec.frame) end
        current_frame = rec.frame
        local hash = hash_value(state_snapshot())
        summary.frames = summary.frames + 1
        if hash == rec.hash then
          summary.matched = summary.matched + 1
        else
          summary.mismatches[#summary.mismatches + 1] =
            { frame = rec.frame, expected = rec.hash, actual = hash }
        end
      end
    end
  end
  local f = io.open(summary_path, 'w')
  if f then f:write(codec.encode(summary)); f:close() end
  print('replayed ' .. summary.frames .. ' frames: ' .. summary.matched .. ' matched')
else
  fail('unknown mode', tostring(mode))
end
"##;

/// The complete driver Lua source (hash helpers + frame driver), written next to the trace.
pub fn game_driver() -> String {
    format!("{HASH_LUA}\n{DRIVER_LUA}")
}

const WORK_DIR: &str = ".rust-anything-game";

fn runtime() -> Result<&'static str> {
    for name in ["luajit", "lua"] {
        if let Ok(out) = Command::new(name).arg("-v").output()
            && out.status.success()
        {
            return Ok(name);
        }
    }
    bail!("no Lua runtime found: install LuaJIT 2.1 (preferred) or Lua 5.1+ on PATH")
}

fn absolute(path: &Path) -> Result<PathBuf> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        Ok(std::env::current_dir()?.join(path))
    }
}

fn prepare_work_dir(trace: &Path) -> Result<PathBuf> {
    let parent = trace
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let work = parent.join(WORK_DIR);
    std::fs::create_dir_all(&work).with_context(|| format!("creating {}", work.display()))?;
    std::fs::write(work.join("rust_anything_codec.lua"), codec())?;
    std::fs::write(
        work.join("rust_anything_headless_stub.lua"),
        headless_stub(),
    )?;
    std::fs::write(work.join("game_driver.lua"), game_driver())?;
    Ok(work)
}

fn driver_command(
    root: &Path,
    trace: &Path,
    frames: usize,
    work: &Path,
    mode: &str,
) -> Result<Command> {
    let root = root
        .canonical()
        .with_context(|| format!("game root {} not found", root.display()))?;
    let mut cmd = Command::new(runtime()?);
    let lua_path = format!(
        "{}/?.lua;{}/?/init.lua;{}/?.lua;{}/?/init.lua",
        work.display(),
        work.display(),
        root.display(),
        root.display()
    );
    cmd.env("LUA_PATH", lua_path)
        .env("RUST_ANYTHING_LUA_ROOT", &root)
        .arg(work.join("game_driver.lua"))
        .arg(mode)
        .arg(&root)
        .arg(trace)
        .arg(frames.to_string())
        .arg(work.join("summary.json"));
    Ok(cmd)
}

fn run_driver(cmd: &mut Command, summary: &Path, what: &str) -> Result<Summary> {
    let output = cmd.output().with_context(|| format!("running {what}"))?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    let parsed = std::fs::read_to_string(summary)
        .ok()
        .and_then(|s| serde_json::from_str::<Summary>(&s).ok());
    if !output.status.success() {
        if let Some(s) = &parsed
            && let Some(e) = &s.error
        {
            bail!("{e}");
        }
        let detail = if stderr.trim().is_empty() {
            stdout.trim()
        } else {
            stderr.trim()
        };
        bail!("{what} failed ({}): {}", output.status, detail);
    }
    parsed.ok_or_else(|| anyhow::anyhow!("{what} did not write {}", summary.display()))
}

pub struct RecordOptions<'a> {
    pub root: &'a Path,
    pub out: &'a Path,
    pub frames: usize,
}

pub struct ReplayOptions<'a> {
    pub root: &'a Path,
    pub trace: &'a Path,
}

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct Mismatch {
    pub frame: usize,
    pub expected: String,
    pub actual: String,
}

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, Default)]
pub struct Summary {
    #[serde(default)]
    pub frames: usize,
    #[serde(default)]
    pub recorded: Option<usize>,
    #[serde(default)]
    pub matched: Option<usize>,
    #[serde(default)]
    pub mismatches: Vec<Mismatch>,
    #[serde(default)]
    pub error: Option<String>,
}

#[derive(Debug, Clone)]
pub struct ReplayOutcome {
    pub frames: usize,
    pub matched: usize,
    pub mismatches: Vec<Mismatch>,
}

impl ReplayOutcome {
    pub fn all_match(&self) -> bool {
        self.frames > 0 && self.matched == self.frames && self.mismatches.is_empty()
    }
}

/// Record `--frames` deterministic frames of the whole app into a JSONL trace.
pub fn record(opts: &RecordOptions<'_>) -> Result<PathBuf> {
    anyhow::ensure!(opts.frames > 0, "--frames must be at least 1");
    let out = absolute(opts.out)?;
    if let Some(parent) = out.parent()
        && !parent.as_os_str().is_empty()
    {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    let work = prepare_work_dir(&out)?;
    let mut cmd = driver_command(opts.root, &out, opts.frames, &work, "record")?;
    let _ = run_driver(&mut cmd, &work.join("summary.json"), "game-record")?;
    Ok(out)
}

/// Replay every frame event from a recorded trace and compare the state hashes.
pub fn replay(opts: &ReplayOptions<'_>) -> Result<ReplayOutcome> {
    let trace = absolute(opts.trace)?;
    anyhow::ensure!(
        trace.exists(),
        "trace {} not found (run game-record first)",
        trace.display()
    );
    let work = prepare_work_dir(&trace)?;
    let mut cmd = driver_command(opts.root, &trace, 0, &work, "replay")?;
    let summary = run_driver(&mut cmd, &work.join("summary.json"), "game-replay")?;
    Ok(ReplayOutcome {
        frames: summary.frames,
        matched: summary.matched.unwrap_or(0),
        mismatches: summary.mismatches,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reuses_headless_stub_and_codec_without_editing_codegen_lua() {
        assert_eq!(headless_stub(), crate::codegen_lua::HEADLESS_STUB_LUA);
        assert_eq!(codec(), crate::codegen_lua::CODEC_LUA);
        assert!(headless_stub().contains("_G.love = stub"));
    }

    #[test]
    fn hash_lua_is_pure_and_driver_wires_the_frame_loop() {
        for needle in [
            "local function fnv_mul",
            "local function fnv_byte",
            "OFFSET_HI, OFFSET_LO = 0xcbf29ce4, 0x84222325",
            "table.sort(keys",
            "MAX_DEPTH = 8",
            "local function hash_value",
        ] {
            assert!(HASH_LUA.contains(needle), "hash module is missing {needle}");
        }
        assert!(
            !HASH_LUA.contains("require('"),
            "hash must not need modules"
        );
        let driver = game_driver();
        for needle in [
            "require('rust_anything_codec')",
            "require('rust_anything_headless_stub')",
            "load_game_file('conf.lua'",
            "load_game_file('main.lua'",
            "pcall(_G.love.load)",
            "['fn'] = 'update'",
            "['fn'] = 'draw'",
            "['fn'] = 'keypressed'",
            "['fn'] = 'mousemoved'",
            "mode == 'record'",
            "mode == 'replay'",
            "codec.decode(line)",
        ] {
            assert!(driver.contains(needle), "driver is missing {needle}");
        }
    }

    #[test]
    fn lua_fnv_matches_independent_reference_vectors() {
        // Verify the pure-Lua hash against Python big-int FNV-1a 64 reference vectors.
        // Skips cleanly when no Lua runtime is installed (the CLI commands report that).
        let Some(lua) = ["luajit", "lua"]
            .into_iter()
            .find(|n| Command::new(n).arg("-v").output().is_ok())
        else {
            eprintln!("skipping Lua hash vector check: no Lua runtime on PATH");
            return;
        };
        let dir =
            std::env::temp_dir().join(format!("rust-anything-game-hash-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let script = dir.join("hash_test.lua");
        let source = format!(
            "{HASH_LUA}\n\
             local cases = {{ {{'', 'cbf29ce484222325'}}, {{'a', 'af63dc4c8601ec8c'}}, {{'hello', 'a430d84680aabd0b'}}, {{'frame:1', 'b339294a2abf175f'}} }}\n\
             for _, c in ipairs(cases) do\n\
               local got = hash_string(c[1])\n\
               assert(got == c[2], c[1] .. ': expected ' .. c[2] .. ', got ' .. got)\n\
             end\n\
             print('FNV vectors OK')\n"
        );
        std::fs::write(&script, source).unwrap();
        let out = Command::new(lua).arg(&script).output().unwrap();
        let _ = std::fs::remove_dir_all(&dir);
        assert!(
            out.status.success(),
            "Lua FNV vectors failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert!(String::from_utf8_lossy(&out.stdout).contains("FNV vectors OK"));
    }

    #[test]
    fn record_then_replay_a_whole_love_app_has_matching_hashes() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/lua_tiny");
        if !root.join("main.lua").exists() {
            return;
        }
        let has_lua = ["luajit", "lua"]
            .iter()
            .any(|n| Command::new(n).arg("-v").output().is_ok());
        if !has_lua {
            eprintln!("skipping whole-app E2E: no Lua runtime on PATH");
            return;
        }
        let dir =
            std::env::temp_dir().join(format!("rust-anything-game-e2e-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let trace = dir.join("trace.jsonl");
        let recorded = record(&RecordOptions {
            root: &root,
            out: &trace,
            frames: 12,
        })
        .unwrap();
        let text = std::fs::read_to_string(&recorded).unwrap();
        let lines: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
        assert_eq!(lines.len(), 12, "one trace line per frame");
        let hashes: std::collections::HashSet<String> = lines
            .iter()
            .filter_map(|l| serde_json::from_str::<serde_json::Value>(l).ok())
            .filter_map(|v| v["hash"].as_str().map(str::to_string))
            .collect();
        assert_eq!(hashes.len(), 12, "every frame must have its own hash");
        let outcome = replay(&ReplayOptions {
            root: &root,
            trace: &trace,
        })
        .unwrap();
        assert!(
            outcome.all_match(),
            "record/replay hashes must match: {outcome:?}"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }
}
